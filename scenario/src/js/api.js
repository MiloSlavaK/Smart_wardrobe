// Привести слово или фразу одежды к именительному падежу с заглавной буквы
function normalizeClothingName(text) {
    if (!text) return "";
    var words = text.trim().split(/\s+/);
    var result = [];
    for (var i = 0; i < words.length; i++) {
        var clean = words[i].toLowerCase().replace(/[?!.,]/g, "");
        var nom = NOMINATIVE_MAP[clean] || clean;
        result.push(nom.charAt(0).toUpperCase() + nom.slice(1));
    }
    return result.join(" ");
}

// Определить категорию по нормализованному названию
function inferCategory(name) {
    if (!name) return "другое";
    var lower = name.toLowerCase().trim();
    if (CATEGORY_MAP[lower]) return CATEGORY_MAP[lower];
    for (var key in CATEGORY_MAP) {
        if (lower.indexOf(key) !== -1) return CATEGORY_MAP[key];
    }
    return "другое";
}

// Извлечь название вещи из сырого текста команды и нормализовать падеж
function extractItemName(text) {
    if (!text) return "";
    var prefixes = [
        "добавь ", "добавить ", "положи ", "положить ",
        "запиши ", "закинь ", "внеси ", "сохрани ",
        "удали ", "удалить ", "убери ", "убрать ",
        "выброси ", "выбросить ",
        "как стирать ", "стирать ",
        "как сложить ", "сложить ",
        "найди ", "найти ", "ищи ", "поищи ", "ищу "
    ];
    var lower = text.toLowerCase().trim();
    for (var i = 0; i < prefixes.length; i++) {
        if (lower.indexOf(prefixes[i]) === 0) {
            var rest = text.slice(prefixes[i].length).trim();
            var normalized = normalizeClothingName(rest);
            if (normalized) return normalized;
        }
    }
    // Последнее слово как запасной вариант
    var words = text.trim().split(/\s+/);
    for (var j = words.length - 1; j >= 0; j--) {
        var w = words[j].replace(/[?!.,]/g, "");
        if (w.length > 2) return normalizeClothingName(w);
    }
    return "";
}
